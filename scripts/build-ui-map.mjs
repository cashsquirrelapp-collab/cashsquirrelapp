// The words on each screen of the app, read from the screens' own code (owner, 2026-11-01: "เวลามีฟีเจอร์อะไรอัปเดต
// เข้าไป น้องค่อนข้างจะไม่รู้ ... อยากให้น้องอัปเดตได้เอง"). เลขากระรอก looks labels up here (backend/src/ai/uiKnowledge.ts),
// so a new button or setting is known the day it ships, without anyone writing it into the knowledge base by hand.
// Only the screens of pages listed below; เลขา itself shows only the pages open to everyone (shared/featureAvailability.ts).
//   npm run ui-map   -> backend/src/ai/generated/uiMap.ts   (tests/ui-map.test.ts fails when it is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FEATURES = path.join(root, 'frontend/src/features');
export const OUT = path.join(root, 'backend/src/ai/generated/uiMap.ts');

/** Which page a screen file belongs to (the page's navigation key). The first rule that matches wins. */
const RULES = [
  [/^dashboard\//, 'dashboard'], [/^mobile\/MobileHome\.tsx$/, 'dashboard'], [/^phone\/PhoneDashboard\.tsx$/, 'dashboard'],
  [/^jobs\//, 'jobs'], [/^import\/(ImportChat|ImportReview)\.tsx$/, 'jobs'],
  [/^calendar\//, 'calendar'], [/^receivables\//, 'receivables'], [/^incomeExpense\//, 'incomeExpense'],
  [/^invoices\//, 'invoice'], [/^vault\/Wht50/, 'wht50'], [/^vault\//, 'vault'],
  [/^settings\//, 'settings'], [/^billing\//, 'plans'], [/^feedback\//, 'feedback'],
  [/^assistant\/(AssistantChat|VoiceComposer|ChatUploadViews|ChatCards)\.tsx$/, 'assistant'],
  [/^goals\//, 'split'], [/^report\//, 'report'], [/^tax\//, 'tax'],
];
// Admin screens, samples and tests are never a customer's screen.
const SKIP = /admin|mock|sample|\.test\.|\.css$/i;
const THAI = /[\u0E00-\u0E7F]/;
// Lines meant for admins, and the word AI (เลขา never calls itself that), stay out even on a customer's screen.
const DROP = /แอดมิน|ผู้ดูแล|admin|\bAI\b/i;

function files(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? files(full) : /\.(tsx|ts)$/.test(entry.name) ? [full] : [];
  });
}

const clean = text => text.replace(/\\n/g, ' ').replace(/\\(['"`])/g, '$1').replace(/\{\d\}/g, '…').replace(/\s+/g, ' ').trim();

/** The Thai words a screen shows: tr()/T()/trc() calls and plain Thai text between JSX tags. */
export function screenWords(source) {
  const out = [];
  for (const match of source.matchAll(/\b(?:tr|T)\(\s*(['"])((?:\\.|(?!\1)[^\\\n])*)\1/g)) out.push(match[2]);
  for (const match of source.matchAll(/\btrc\(\s*['"][^'"\n]*['"]\s*,\s*(['"])((?:\\.|(?!\1)[^\\\n])*)\1/g)) out.push(match[2]);
  for (const match of source.matchAll(/>\s*([^<>{}\n=();'"`]*[\u0E00-\u0E7F][^<>{}\n=();'"`]*?)\s*</g)) out.push(match[1]);
  return out.map(clean).filter(text => THAI.test(text) && !DROP.test(text) && text.length >= 2 && text.length <= 90 && !text.includes('${'));
}

export function buildUiMap() {
  const map = new Map();
  for (const file of files(FEATURES).sort()) {
    const rel = path.relative(FEATURES, file).split(path.sep).join('/');
    if (SKIP.test(rel)) continue;
    const area = RULES.find(([rule]) => rule.test(rel))?.[1];
    if (!area) continue;
    const words = map.get(area) ?? new Set();
    for (const text of screenWords(fs.readFileSync(file, 'utf8'))) words.add(text);
    map.set(area, words);
  }
  const body = [...map.keys()].sort().map(area => `  ${JSON.stringify(area)}: ${JSON.stringify([...map.get(area)].sort((a, b) => a.localeCompare(b, 'th')))},`).join('\n');
  return `// Generated by scripts/build-ui-map.mjs from the screens in frontend/src/features. Do not edit; run \`npm run ui-map\`.\n`
    + `// The words each page shows, by the page's navigation key (see the script for which files count).\n`
    + `export const UI_MAP: Readonly<Record<string, readonly string[]>> = {\n${body}\n};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = buildUiMap();
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const before = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (before !== text) fs.writeFileSync(OUT, text);
  console.log(`ui-map: ${before === text ? 'up to date' : 'written'} (${(text.length / 1024).toFixed(0)} KB)`);
}
