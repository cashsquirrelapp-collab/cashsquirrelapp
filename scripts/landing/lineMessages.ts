// Builds the two LINE messages shown on the landing page by calling the app's own message builders.
//
//   npx tsx scripts/landing/lineMessages.ts      (after capture.ts, which writes jobs-after.gen.json)
//
// Nothing is sent to LINE. The jobs are the sample jobs exactly as the app saved them after the
// second instalment was recorded during the capture, so the amounts continue the story on the page.
// Output: frontend/src/features/marketing/landing/story/line.gen.ts
import fs from 'node:fs';
import path from 'node:path';
import { CAPTURE_NOW } from './sampleData';
import type { Job } from '../../shared/types';

// The same "today" as the screenshots.
const FIXED = new Date(CAPTURE_NOW).getTime();
const RealDate = Date;
// eslint-disable-next-line @typescript-eslint/no-explicit-any
(globalThis as any).Date = class extends RealDate { constructor(...args: any[]) { if (args.length) super(...(args as [any])); else super(FIXED); } static now() { return FIXED; } };
process.env.TZ = 'Asia/Bangkok';
process.env.APP_URL = 'https://kraroktunngern.vercel.app';

const ROOT = path.resolve(import.meta.dirname, '../..');
const jobs: Job[] = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts/landing/jobs-after.gen.json'), 'utf8'));
const { buildUnpaidJobsMessage } = await import('../../backend/src/services/lineAssistant');
const { buildDigestFlexMessage } = await import('../../backend/src/handlers/send-overdue-digest');
const { getRelativeDaysText } = await import('../../shared/calendar');

// The part of lineAssistant's buildDataSnapshot (not exported) that feeds the "รอรับเงิน" card.
const unpaidJobs = jobs.filter(j => (j.pending || 0) > 0 && j.status !== 'done');
const snapshot = {
  unpaid: unpaidJobs.map(j => ({ name: j.name, client: j.client || '', pending: j.pending || 0, dueDate: j.payDate || null, dueText: j.payDate ? getRelativeDaysText(j.payDate).text : 'ไม่ระบุวันครบกำหนด' })),
  totalPendingAllTime: unpaidJobs.reduce((sum, j) => sum + (j.pending || 0), 0),
};
// The part of send-overdue-digest's findJobsNeedingAttention (not exported): overdue, due today, or due within 2 days.
const days = (date: string) => Math.round((new RealDate(`${date}T00:00:00+07:00`).getTime() - new RealDate(`${new RealDate(FIXED + 7 * 3600e3).toISOString().slice(0, 10)}T00:00:00+07:00`).getTime()) / 86400e3);
const attention = jobs.flatMap(j => {
  if (j.installments?.length) return j.installments.flatMap(row => (row.status === 'paid' || row.amount <= 0 || !row.dueDate || days(row.dueDate) > 2) ? [] : [{ ...j, id: `${j.id}:${row.id}`, name: `${j.name} • ${row.label}`, pending: row.amount, dueDate: row.dueDate, payDate: row.dueDate, diffDays: days(row.dueDate) }]);
  return (j.pending <= 0 || !j.payDate || days(j.payDate) > 2) ? [] : [{ ...j, diffDays: days(j.payDate) }];
});

// eslint-disable-next-line @typescript-eslint/no-explicit-any
const unpaid = buildUnpaidJobsMessage(snapshot as any) as any;
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const digest = buildDigestFlexMessage(attention as any) as any;
// The card art is served by this app; point at it by path so the page does not depend on the host name.
const local = (value: unknown): unknown => JSON.parse(JSON.stringify(value).replaceAll('https://kraroktunngern.vercel.app/', '/'));

const out = path.join(ROOT, 'frontend/src/features/marketing/landing/story/line.gen.ts');
fs.writeFileSync(out, `// Generated by scripts/landing/lineMessages.ts from the app's own LINE message builders
// (buildUnpaidJobsMessage in lineAssistant.ts, buildDigestFlexMessage in send-overdue-digest.ts),
// with the sample jobs as the app saved them. Do not edit by hand.
export const LINE_UNPAID = ${JSON.stringify(local(unpaid), null, 2)} as const;

export const LINE_DIGEST = ${JSON.stringify(local(digest), null, 2)} as const;
`);
console.log('unpaid:', unpaid.altText, '| digest:', digest.altText);
